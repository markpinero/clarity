import Foundation

public enum DisplayTransform {
  public static func apply(
    adjustment: DisplayAdjustment,
    to baseline: RGBTransferTable
  ) -> RGBTransferTable {
    apply(factors: factors(for: adjustment), to: baseline)
  }

  public static func factors(for adjustment: DisplayAdjustment) -> ChannelFactors {
    let temperature = temperatureFactors(for: adjustment.kelvin)
    return ChannelFactors(red: temperature.red, green: temperature.green, blue: temperature.blue)
      .scaled(by: adjustment.brightness)
  }

  public static func apply(
    factors: ChannelFactors,
    to baseline: RGBTransferTable
  ) -> RGBTransferTable {
    RGBTransferTable(
      validatedRed: baseline.red.map { clamp($0 * factors.red) },
      green: baseline.green.map { clamp($0 * factors.green) },
      blue: baseline.blue.map { clamp($0 * factors.blue) }
    )
  }

  private static func temperatureFactors(for kelvin: Int) -> (red: Float, green: Float, blue: Float)
  {
    let clampedKelvin = min(max(kelvin, 0), 10_000)
    let lowerIndex = clampedKelvin / 100
    let upperIndex = min(lowerIndex + 1, irisWhitePoints.count - 1)
    let progress = Float(clampedKelvin % 100) / 100
    let lower = irisWhitePoints[lowerIndex]
    let upper = irisWhitePoints[upperIndex]

    return (
      lower.red + (upper.red - lower.red) * progress,
      lower.green + (upper.green - lower.green) * progress,
      lower.blue + (upper.blue - lower.blue) * progress
    )
  }

  private static func clamp(_ value: Float) -> Float {
    min(max(value, 0), 1)
  }

